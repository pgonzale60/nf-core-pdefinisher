from __future__ import annotations

from typing import Dict, List, Any
from .models import EditValidationResult, FlagrantError
from .policy import get_script_fingerprint, __version__


def generate_validation_json(
    sample: str,
    edit_results: List[EditValidationResult],
    flagrant_errors: List[FlagrantError],
    total_svs_called: int,
) -> Dict[str, Any]:
    """Builds a structured dictionary payload for validation."""
    passed_edits = sum(1 for r in edit_results if r.status == "PASS")
    warn_edits = sum(1 for r in edit_results if r.status == "WARN")
    fail_edits = sum(1 for r in edit_results if r.status == "FAIL")

    edit_records = []
    for r in edit_results:
        conflicting = [
            {
                "id": s.sv_id,
                "type": s.sv_type,
                "len": s.sv_len,
                "vaf": s.vaf,
                "support": s.support
            }
            for s in r.conflicting_svs
        ]
        edit_records.append({
            "card_id": r.region.card_id,
            "chrom": r.region.chrom,
            "action": r.region.action,
            "edit_type": r.region.edit_type,
            "curated_start": r.region.curated_start,
            "curated_end": r.region.curated_end,
            "delta_bp": r.region.delta_bp,
            "status": r.status,
            "mean_coverage": r.mean_coverage,
            "spanning_reads": r.spanning_reads,
            "conflicting_svs_count": len(r.conflicting_svs),
            "conflicting_svs": conflicting,
            "explanation": r.explanation,
        })

    error_records = []
    for e in flagrant_errors:
        error_records.append({
            "chrom": e.chrom,
            "start": e.start,
            "end": e.end,
            "type": e.error_type,
            "severity": e.severity,
            "details": e.details,
            "description": e.description,
        })

    return {
        "sample": sample,
        "engine_version": __version__,
        "fingerprint": get_script_fingerprint(),
        "summary": {
            "total_edits_evaluated": len(edit_results),
            "edits_passed": passed_edits,
            "edits_warned": warn_edits,
            "edits_failed": fail_edits,
            "edit_concordance_pct": round((passed_edits / len(edit_results) * 100.0), 1) if edit_results else 100.0,
            "total_svs_called": total_svs_called,
            "flagrant_errors_count": len(flagrant_errors),
        },
        "edited_regions_validation": edit_records,
        "flagrant_assembly_errors": error_records,
    }


def render_validation_markdown(data: Dict[str, Any]) -> str:
    """Renders the executive Markdown validation dossier."""
    sample = data.get("sample", "unknown")
    summary = data.get("summary", {})
    edits = data.get("edited_regions_validation", [])
    errors = data.get("flagrant_assembly_errors", [])

    lines = []
    lines.append(f"# Post-Curation Mapping & SV Validation Dossier: `{sample}`\n")
    lines.append(f"*Generated by PDE Curation Validation Engine v{data.get('engine_version')} (sha256:{data.get('fingerprint')})*\n")

    # Executive KPI
    lines.append("## 1. Executive Quality & Concordance Summary\n")
    lines.append(f"* **Total Evaluated Surgery Loci**: `{summary.get('total_edits_evaluated', 0)}`")
    lines.append(f"* **Surgery Loci Concordance**: `{summary.get('edit_concordance_pct', 0.0)}%` ({summary.get('edits_passed', 0)} Clean, {summary.get('edits_warned', 0)} Warnings, {summary.get('edits_failed', 0)} Rejected)")
    lines.append(f"* **Total Assembly SVs Called (Sniffles)**: `{summary.get('total_svs_called', 0)}`")
    lines.append(f"* **Flagrant Homozygous Errors (Unedited Loci, $VAF \\ge 0.8$)**: `{summary.get('flagrant_errors_count', 0)}`\n")

    # Edited Loci Table
    lines.append("## 2. Surgery Loci Physical Verification Ledger\n")
    lines.append("| Chrom | Surgery / Edit Type | Curated Span | Delta | Status | Cov | Spanning | Diagnostics / Verdict |")
    lines.append("| :--- | :--- | :--- | :---: | :---: | :---: | :---: | :--- |")

    if not edits:
        lines.append("| - | *No surgical modifications performed* | - | - | PASS | - | - | Baseline assembly unmodified |")
    else:
        for e in edits:
            status_badge = f"**{e['status']}**" if e['status'] == "PASS" else f"<span style='color:orange;'>**{e['status']}**</span>"
            span_str = f"{e['chrom']}:{e['curated_start']:,}-{e['curated_end']:,}"
            delta_str = f"+{e['delta_bp']:,} bp" if e['delta_bp'] > 0 else f"{e['delta_bp']:,} bp"
            is_purged = "PURGE" in e.get("action", "").upper() or "PURGE" in e.get("edit_type", "").upper()
            cov_str = "-" if is_purged else f"{e['mean_coverage']}x"
            span_reads_str = "-" if is_purged else str(e['spanning_reads'])
            lines.append(
                f"| **{e['chrom']}** | {e['edit_type']} | {span_str} | {delta_str} | {status_badge} | {cov_str} | {span_reads_str} | {e['explanation']} |"
            )
    lines.append("\n")

    # Flagrant Assembly Errors
    lines.append("## 3. Flagrant Assembly Error Registry (Unedited Loci, $VAF \\ge 0.8$, High Support)\n")
    if not errors:
        lines.append("> [!NOTE]\n> **No flagrant homozygous structural defects detected across the curated assembly.**\n")
    else:
        lines.append("| Locus | Error Type | Severity | SV Class | Size | VAF | Reads | Details |")
        lines.append("| :--- | :--- | :---: | :---: | :---: | :---: | :---: | :--- |")
        for err in errors:
            loc = f"{err['chrom']}:{err['start']:,}-{err['end']:,}"
            d = err.get("details", {})
            lines.append(
                f"| `{loc}` | {err['type']} | **{err['severity']}** | {d.get('sv_type', 'SV')} | {d.get('sv_len', 0):,} bp | {d.get('vaf', 0.0)} | {d.get('support', 0)} | {err['description']} |"
            )
        lines.append("\n")

    return "\n".join(lines) + "\n"
